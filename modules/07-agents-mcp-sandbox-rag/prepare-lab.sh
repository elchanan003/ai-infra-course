#!/usr/bin/env bash
# Module 07 prepare: profiles gw+mock+llm+rag+store, mock-chat script for mock-vllm A, lab gateway key,
# lab/env.sh, the decoy socket used by the troubleshooting task. Idempotent; never touches your lab/ files
# (except lab/env.sh, which is generated).
set -uo pipefail
MODULE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$MODULE_DIR/../../platform/lib.sh"
ST="$MODULE_DIR/.state"
PY="$PLATFORM_DIR/.venv/bin/python"
LAB_KEY_VALUE="sk-lab07-student"

[ -x "$PY" ] || { echo "prepare-lab: $PY missing (run platform/setup.sh)"; exit 1; }
docker image inspect "$PYTHON_IMAGE" >/dev/null 2>&1 || { echo "prepare-lab: image $PYTHON_IMAGE is not pulled (platform/setup.sh)"; exit 1; }

mkdir -p "$ST/mock-a" "$ST/run"
cp -f "$PLATFORM_DIR/stack/config/mock-vllm-a/args" "$PLATFORM_DIR/stack/config/mock-vllm-a/gpu.yaml" "$ST/mock-a/"
cp -f "$MODULE_DIR/.verify/mock-a-script.yaml" "$ST/mock-a/script.yaml"
chmod -R a+rX "$ST/mock-a" "$MODULE_DIR/lab"

MOCK_VLLM_A_CONFIG_DIR="$ST/mock-a" "$PLATFORM_DIR/stack.sh" up gw mock llm rag store \
  || { echo "prepare-lab: stack did not come up healthy (see: platform/stack.sh status)"; exit 1; }
wait_http "$LITELLM_URL/health/liveliness" 90 && wait_http "$QDRANT_URL/readyz" 60 && wait_http "$TRIPWIRE_URL/health" 60 \
  || { echo "prepare-lab: gateway, Qdrant or tripwire not ready"; exit 1; }
curl -fsS -o /dev/null -X DELETE "$MOCK_A_URL/admin/stats" || true
curl -fsS -o /dev/null -X DELETE "$MOCK_A_URL/admin/fault" || true

# lab key limited to the two aliases this module needs
have=$(litellm_api "/key/info?key=$LAB_KEY_VALUE" | jq -r '.info.key_alias // empty' 2>/dev/null)
if [ -z "$have" ]; then
  litellm_api /key/generate -d "{\"key\":\"$LAB_KEY_VALUE\",\"key_alias\":\"lab07\",\"models\":[\"mock-a\",\"embed\"]}" >/dev/null
fi
[ "$(litellm_code "$LAB_KEY_VALUE" mock-a ping)" = 200 ] || { echo "prepare-lab: lab key does not work on alias mock-a"; exit 1; }

# decoy "docker socket" for the troubleshooting task: a real unix socket FILE, nobody listens on it
rm -rf "$ST/run/dockerd.sock"
"$PY" -c "import socket,sys; s=socket.socket(socket.AF_UNIX); s.bind(sys.argv[1]); s.close()" "$ST/run/dockerd.sock"

cat > "$MODULE_DIR/lab/env.sh" <<ENV
# generated by prepare-lab.sh - do not edit
export GATEWAY=$LITELLM_URL
export LAB_KEY=$LAB_KEY_VALUE
export AGENT_MODEL=mock-a
export EMBED_MODEL=embed
export QDRANT_URL=$QDRANT_URL
export SANDBOX_IMAGE=$PYTHON_IMAGE
export TICKETS_JSON=$MODULE_DIR/lab/agent/tickets.json
# ports for your own dev servers (verify uses 18130-18132): 18133 18134
ENV
cat <<MSG
prepare-lab: ready.
  source lab/env.sh        # GATEWAY LAB_KEY AGENT_MODEL EMBED_MODEL QDRANT_URL SANDBOX_IMAGE TICKETS_JSON
  agent model  mock-a  (SIMULATED: scripted mock-chat; embeddings: real llama.cpp bge-small via alias embed)
  Qdrant       $QDRANT_URL      tripwire counter  $TRIPWIRE_URL/hits
MSG
